"""Destructive-write tests, opt-in only for a disposable PostgreSQL/PostGIS DB.

Provision migrations 1 and 2 manually on a database named with `test` or
`disposable`, then set both FIRENEXUS_TEST_DATABASE_URL and
FIRENEXUS_ALLOW_DATABASE_TESTS=1. Tests never run migrations themselves.
"""
import csv
import io
import os
from concurrent.futures import ThreadPoolExecutor
from datetime import date
import uuid

import pytest

from app.services.database import connection
from app.services.existing_csv_import import ExistingCsvImportError, ExistingCsvImporter, ImportProvenance
from app.services.registry import DatasetRegistry

DATABASE_URL = os.getenv("FIRENEXUS_TEST_DATABASE_URL", "")
ENABLED = os.getenv("FIRENEXUS_ALLOW_DATABASE_TESTS") == "1" and bool(DATABASE_URL)


def _source(path, sensor="MODIS"):
    if sensor == "VIIRS":
        columns = ["latitude", "longitude", "bright_ti4", "scan", "track", "acq_date", "acq_time",
                   "satellite", "confidence", "version", "bright_ti5", "frp", "daynight"]
        row = ["-3.25", "-60.5", "320", "1", "1", "2024-02-03", "45", "Suomi-NPP", "n", "2.0N", "290", "12", "D"]
        with path.open("w", newline="", encoding="utf-8") as stream:
            writer = csv.writer(stream)
            writer.writerow(columns)
            writer.writerow(row)
        return path
    columns = ["latitude", "longitude", "brightness", "scan", "track", "acq_date", "acq_time",
               "satellite", "confidence", "version", "bright_t31", "frp", "daynight"]
    row = ["-3.25", "-60.5", "320", "1", "1", "2024-02-03", "45", "Terra", "85", "6.1N", "290", "12", "D"]
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream)
        writer.writerow(columns)
        writer.writerow(row)
    return path


def _service(tmp_path, data_dir=None):
    data_dir = data_dir or tmp_path / "store"
    registry = DatasetRegistry(str(data_dir), database_url=DATABASE_URL,
                               ssl_ca=os.getenv("DATABASE_SSL_CA", ""))
    service = ExistingCsvImporter(registry, data_dir, 10_000_000, DATABASE_URL,
                                  os.getenv("DATABASE_SSL_CA", ""))
    return service, registry


@pytest.fixture(scope="module", autouse=True)
def require_disposable_database():
    if not ENABLED:
        pytest.skip("Explicit disposable DB opt-in required; no migration is run by tests")
    with connection(DATABASE_URL, os.getenv("DATABASE_SSL_CA", "")) as conn:
        name = conn.execute("SELECT current_database() AS name").fetchone()["name"].lower()
        assert "test" in name or "disposable" in name, "Refusing writes unless database name includes test/disposable"
        assert conn.execute("SELECT to_regclass('public.datasets') AS name").fetchone()["name"]
        assert conn.execute("SELECT to_regclass('public.dataset_imports') AS name").fetchone()["name"], \
            "Apply migration 2 manually to this disposable database before running these tests"


def _cleanup(source_hash):
    # Restrict cleanup to the exact test file checksum generated by this test.
    with connection(DATABASE_URL, os.getenv("DATABASE_SSL_CA", "")) as conn:
        conn.execute("DELETE FROM dataset_imports WHERE source_sha256=%s", (source_hash,))
        conn.execute("DELETE FROM datasets WHERE source_checksum_sha256=%s", (source_hash,))


def _import(source, data_dir, expected=1, end_date=date(2024, 2, 28), registry=None):
    service, registry = _service(source.parent, data_dir)
    if registry is not None:
        service.registry = registry
    return service.import_file(source,
        ImportProvenance("amazon_basin", "MODIS_SP", date(2024, 2, 1), end_date), expected)


@pytest.mark.parametrize("mode", ["repeat", "provenance_conflict"])
def test_import_and_idempotent_or_conflicting_retry(tmp_path, mode):
    source = _source(tmp_path / f"{uuid.uuid4().hex}.csv")
    service, _ = _service(tmp_path)
    digest = __import__("app.services.existing_csv_import", fromlist=["sha256_file"]).sha256_file(source)
    try:
        first = service.import_file(source, ImportProvenance("amazon_basin", "MODIS_SP", date(2024, 2, 1), date(2024, 2, 28)), 1)
        assert first["status"] == "imported" and first["parsedRows"] == 1
        if mode == "repeat":
            repeated = service.import_file(source, ImportProvenance("amazon_basin", "MODIS_SP", date(2024, 2, 1), date(2024, 2, 28)), 1)
            assert repeated["status"] == "already_imported"
            assert repeated["datasetId"] == first["datasetId"]
        else:
            with pytest.raises(ExistingCsvImportError, match="different acquisition provenance"):
                service.import_file(source, ImportProvenance("amazon_basin", "MODIS_SP", date(2024, 2, 2), date(2024, 2, 28)), 1)
    finally:
        _cleanup(digest)


def test_successful_viirs_import_preserves_categorical_confidence(tmp_path):
    source = _source(tmp_path / f"{uuid.uuid4().hex}.csv", "VIIRS")
    service, registry = _service(tmp_path)
    digest = __import__("app.services.existing_csv_import", fromlist=["sha256_file"]).sha256_file(source)
    try:
        result = service.import_file(source,
            ImportProvenance("amazon_basin", "VIIRS_SNPP_SP", date(2024, 2, 1), date(2024, 2, 28)), 1)
        assert result["status"] == "imported" and result["parsedRows"] == 1
        rows = registry.query_observations(dataset_ids=[result["datasetId"]])
        assert len(rows) == 1
        assert rows[0].source == "VIIRS" and rows[0].platform == "Suomi-NPP"
        assert rows[0].confidence is None and rows[0].confidence_class == "n"
    finally:
        _cleanup(digest)


def test_concurrent_same_file_import_is_one_dataset(tmp_path):
    source = _source(tmp_path / f"{uuid.uuid4().hex}.csv")
    digest = __import__("app.services.existing_csv_import", fromlist=["sha256_file"]).sha256_file(source)
    try:
        with ThreadPoolExecutor(max_workers=2) as pool:
            results = list(pool.map(lambda _: _import(source, tmp_path / f"store-{uuid.uuid4().hex}"), range(2)))
        assert sorted(result["status"] for result in results) == ["already_imported", "imported"]
        assert len({result["datasetId"] for result in results}) == 1
        with connection(DATABASE_URL, os.getenv("DATABASE_SSL_CA", "")) as conn:
            assert conn.execute("SELECT COUNT(*) AS n FROM dataset_imports WHERE source_sha256=%s", (digest,)).fetchone()["n"] == 1
    finally:
        _cleanup(digest)


def test_database_failure_rolls_back_dataset_and_records_retryable_failure(tmp_path, monkeypatch):
    source = _source(tmp_path / f"{uuid.uuid4().hex}.csv")
    digest = __import__("app.services.existing_csv_import", fromlist=["sha256_file"]).sha256_file(source)
    service, _ = _service(tmp_path)
    original = service.registry._index_jsonl_postgres

    def fail_after_dataset_insert(dataset_id, path, replace=False, connection=None, meta=None):
        connection.execute("INSERT INTO datasets(id,title,sensor,metadata,provenance) VALUES (%s,%s,%s,'{}'::jsonb,'{}'::jsonb)",
                           (dataset_id, "rollback fixture", "MODIS"))
        raise RuntimeError("synthetic transactional failure")

    monkeypatch.setattr(service.registry, "_index_jsonl_postgres", fail_after_dataset_insert)
    try:
        with pytest.raises(Exception, match="no dataset was committed"):
            service.import_file(source, ImportProvenance("amazon_basin", "MODIS_SP", date(2024, 2, 1), date(2024, 2, 28)), 1)
        with connection(DATABASE_URL, os.getenv("DATABASE_SSL_CA", "")) as conn:
            assert conn.execute("SELECT COUNT(*) AS n FROM datasets WHERE source_checksum_sha256=%s", (digest,)).fetchone()["n"] == 0
            state = conn.execute("SELECT import_status,failure_code FROM dataset_imports WHERE source_sha256=%s", (digest,)).fetchone()
            assert state["import_status"] == "failed"
            assert state["failure_code"] == "DATABASE_IMPORT_FAILED"
    finally:
        monkeypatch.setattr(service.registry, "_index_jsonl_postgres", original)
        _cleanup(digest)
